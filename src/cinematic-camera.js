export function cameraAt(position,mobile=false,reduced=false){
 const p=Math.max(0,Math.min(shots.length-1,position)),i=Math.floor(p),j=Math.min(i+1,shots.length-1),t=p-i,e=t*t*(3-2*t);
 const a=shots[i],b=shots[j],mix=k=>a[k]+(b[k]-a[k])*e;
 if(reduced)return {x:0,y:0,scale:1,label:a[3]};
 const factor=mobile?.42:1;
 return {x:mix(0)*factor,y:mix(1)*factor,scale:mobile?1+(mix(2)-1)*.56:mix(2),label:a[3]};
}
